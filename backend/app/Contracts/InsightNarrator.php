<?php

namespace App\Contracts;

use App\Services\Intelligence\Insight;

/**
 * Words an insight for people (docs/AI_ARCHITECTURE.md).
 *
 * The facts of an insight are computed by DORY from the business's own
 * records; a narrator only turns them into a title and a sentence in the
 * reader's language. The built-in TemplateInsightNarrator uses translated
 * templates. A language-model narrator can implement this contract later:
 * it receives only the aggregated facts (no names, phone numbers or ids),
 * must fall back to the templates when the model fails, and is selected
 * with DORY_AI_NARRATOR, so no caller changes.
 */
interface InsightNarrator
{
    /**
     * @return array{title: string, body: string}
     */
    public function narrate(Insight $insight, string $locale): array;

    /**
     * Shown to the business as "generated by", e.g. "template".
     */
    public function name(): string;
}
